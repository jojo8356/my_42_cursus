/* Comme strcmp : renvoie la difference entre les premiers caracteres
   divergents (comparaison en unsigned char), 0 si chaines egales. */
int	ft_strcmp(char *s1, char *s2)
{
	int	i;

	i = 0;
	while (s1[i] && s2[i] && s1[i] == s2[i])
		i++;
	return ((unsigned char)s1[i] - (unsigned char)s2[i]);
}
