#!/usr/bin/env python3
"""Generate a large differential test table comparing ft_printf to libc printf.

Each case formats a SINGLE conversion so the runner can dispatch the argument
with the correct C type. Flags are emitted in every subset/order combination.
"""
import itertools

FLAGS = ['-', '0', '#', '+', ' ']
WIDTHS = ["", "5", "10", "*"]
PRECS = ["", ".", ".3", ".8", ".*"]

NUM_VALUES = [0, 1, -1, 42, -42, 2147483647, -2147483648]
PTR_VALUES = [0, 1, 0x1234, 0xDEADBEEF, -1, 0x7FFFFFFFFFFF]
STR_VALUES = ['""', '"a"', '"hello"', '"42 school"', '"un peu plus long"',
              '"x"', 'NULL']
CHAR_VALUES = [0, 65, 97, 127, 255, -1]

cases = []


def flag_subsets(chars):
    out = []
    for mask in range(1 << len(chars)):
        out.append("".join(c for j, c in enumerate(chars) if mask & (1 << j)))
    return out


def add(fmt, conv, val=0, sval="NULL", w=0, p=0, mode=0):
    cases.append((fmt, conv, val, sval, w, p, mode))


def numeric(conv, values):
    for flags in flag_subsets(FLAGS):
        for wi, width in enumerate(WIDTHS):
            for pi, prec in enumerate(PRECS):
                for k, v in enumerate(values):
                    mode = (1 if width == "*" else 0) | (2 if prec == ".*" else 0)
                    w = 7 if k % 2 == 0 else -7
                    p = 4 if k % 2 == 0 else -3
                    fmt = "%" + flags + width + prec + conv
                    add(fmt, conv, val=v, w=w, p=p, mode=mode)


for conv in ['d', 'i', 'u', 'x', 'X']:
    numeric(conv, NUM_VALUES)

# %p : all flag subsets, widths, precisions
for flags in flag_subsets(FLAGS):
    for width in WIDTHS:
        for prec in PRECS:
            for k, v in enumerate(PTR_VALUES):
                mode = (1 if width == "*" else 0) | (2 if prec == ".*" else 0)
                w = 12 if k % 2 == 0 else -12
                p = 6 if k % 2 == 0 else -4
                fmt = "%" + flags + width + prec + "p"
                add(fmt, 'p', val=v, w=w, p=p, mode=mode)

# %s : '-' and '0' flags, widths, precisions (other flags ignored by libc)
for flags in flag_subsets(['-', '0']):
    for width in WIDTHS:
        for prec in PRECS:
            for k, sval in enumerate(STR_VALUES):
                mode = (1 if width == "*" else 0) | (2 if prec == ".*" else 0)
                w = 9 if k % 2 == 0 else -9
                p = 4 if k % 2 == 0 else -2
                fmt = "%" + flags + width + prec + "s"
                add(fmt, 's', sval=sval, w=w, p=p, mode=mode)

# %c : '-' and '0' flags, widths (precision is not applicable to %c)
for flags in flag_subsets(['-', '0']):
    for width in ["", "1", "5", "*"]:
        for k, v in enumerate(CHAR_VALUES):
            mode = 1 if width == "*" else 0
            w = 6 if k % 2 == 0 else -6
            fmt = "%" + flags + width + "c"
            add(fmt, 'c', val=v, w=w, mode=mode)

# %% : a few literal / flagged forms (libc ignores width/precision for %)
for fmt in ["%%", " %% ", "%%%%", "%% %% %%", "%5%", "%-5%", "%05%", "%.5%"]:
    add(fmt, '%')

with open("cases.h", "w") as f:
    f.write("/* Auto-generated by generate_tests.py -- do not edit. */\n")
    f.write("static const t_case g_cases[] = {\n")
    for fmt, conv, val, sval, w, p, mode in cases:
        f.write('\t{"%s", \'%s\', %dLL, %s, %d, %d, %d},\n'
                % (fmt, conv, val, sval, w, p, mode))
    f.write("};\n")
    f.write("#define CASE_COUNT %d\n" % len(cases))

print("generated %d cases" % len(cases))
