#include "libft.h"

char	*ft_strrchr(const char *s, int c)
{
	unsigned char	target;
	const char		*last;

	target = (unsigned char)c;
	last = NULL;
	while (*s != '\0')
	{
		if ((unsigned char)*s == target)
			last = s;
		s++;
	}
	if (target == '\0')
		return ((char *)s);
	return ((char *)last);
}
